package com.osscabinet.ossWallet.data.local.query

import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.osscabinet.ossWallet.data.local.AppDatabase
import com.osscabinet.ossWallet.data.local.entity.AccountEntity
import com.osscabinet.ossWallet.data.local.entity.CategoryEntity
import com.osscabinet.ossWallet.data.local.entity.TransactionEntity
import com.osscabinet.ossWallet.domain.model.TransactionFilter
import com.osscabinet.ossWallet.domain.model.TransactionType
import com.osscabinet.ossWallet.domain.model.query.AggregationDimension
import com.osscabinet.ossWallet.domain.model.query.StandardMetrics
import com.osscabinet.ossWallet.domain.service.query.AggregationPlanner
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.math.BigDecimal

/**
 * Integration tests for [DatabaseQueryServiceImpl]. Verifies that the SQL grammar generated by
 * [TransactionQueryBuilder] and executed via [TransactionDao] produces correct results against a
 * real (in-memory) Room database.
 *
 * No SQLCipher passphrase is needed for in-memory databases.
 */
@RunWith(AndroidJUnit4::class)
class DatabaseQueryServiceImplTest {

    private lateinit var db: AppDatabase
    private lateinit var service: DatabaseQueryServiceImpl

    private val profileId = 1
    private val otherProfileId = 2

    @Before
    fun setup() = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        db = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .allowMainThreadQueries()
            .build()

        service = DatabaseQueryServiceImpl(
            transactionDao = db.transactionDao(),
            queryBuilder = TransactionQueryBuilder(),
            planner = AggregationPlanner(),
            cache = QueryCache(),
            json = kotlinx.serialization.json.Json { ignoreUnknownKeys = true },
            invalidationTracker = db.invalidationTracker
        )

        // Seed prerequisite rows for FK constraints.
        db.accountDao().upsertAccount(
            AccountEntity(
                id = "acc1", name = "Checking", currencyCode = "USD",
                structureType = "STANDARD", colorHex = "#fff", icon = "bank",
                allowedCurrencies = "", profileId = profileId
            )
        )
        db.categoryDao().insertCategory(
            CategoryEntity(
                id = 1L,
                name = "Food",
                iconName = "food",
                colorHex = 0,
                isDefault = false
            )
        )
    }

    @After
    fun tearDown() {
        db.close()
    }

    // ─────────────────────────────────────────────────────────────────────────
    // observeFilteredTransactions
    // ─────────────────────────────────────────────────────────────────────────

    @Test
    fun observeFilteredTransactions_returnsOnlyMatchingProfileTransactions() = runBlocking {
        insert(tx("T1", profileId = profileId, amount = "100.00", type = TransactionType.INCOME))
        insert(
            tx(
                "T2",
                profileId = otherProfileId,
                amount = "200.00",
                type = TransactionType.INCOME
            )
        )

        val results = service.observeFilteredTransactions(
            profileId = profileId,
            filter = TransactionFilter()
        ).first()

        assertEquals(1, results.size)
        assertEquals("T1", results[0].name)
    }

    @Test
    fun observeFilteredTransactions_respectsLimitParameter() = runBlocking {
        repeat(5) { i ->
            insert(
                tx(
                    "T$i", profileId = profileId, timestamp = i.toLong(),
                    amount = "10.00", type = TransactionType.INCOME
                )
            )
        }

        val results = service.observeFilteredTransactions(
            profileId = profileId,
            filter = TransactionFilter(),
            limit = 2
        ).first()

        assertEquals(2, results.size)
    }

    // ─────────────────────────────────────────────────────────────────────────
    // getMinTransactionTimestamp
    // ─────────────────────────────────────────────────────────────────────────

    @Test
    fun getMinTransactionTimestamp_returnsEarliestTimestamp() = runBlocking {
        insert(
            tx(
                "Early", profileId = profileId, timestamp = 1000L,
                amount = "10.00", type = TransactionType.INCOME
            )
        )
        insert(
            tx(
                "Late", profileId = profileId, timestamp = 9000L,
                amount = "10.00", type = TransactionType.INCOME
            )
        )

        val result = service.getMinTransactionTimestamp(profileId)

        assertEquals(1000L, result)
    }

    @Test
    fun getMinTransactionTimestamp_returnsNullWhenNoTransactions() = runBlocking {
        val result = service.getMinTransactionTimestamp(profileId)
        assertNull(result)
    }

    @Test
    fun getMinTransactionTimestamp_isolatesProfileData() = runBlocking {
        insert(
            tx(
                "OtherProfile", profileId = otherProfileId, timestamp = 500L,
                amount = "10.00", type = TransactionType.INCOME
            )
        )
        insert(
            tx(
                "ThisProfile", profileId = profileId, timestamp = 2000L,
                amount = "10.00", type = TransactionType.INCOME
            )
        )

        val result = service.getMinTransactionTimestamp(profileId)

        assertEquals(2000L, result)
    }

    // ─────────────────────────────────────────────────────────────────────────
    // aggregate — SQL grammar verification
    // ─────────────────────────────────────────────────────────────────────────

    @Test
    fun aggregate_sumsByCurrency_producesCorrectTotals() = runBlocking {
        insert(
            tx(
                "USD1", profileId = profileId, amount = "100.00",
                type = TransactionType.INCOME, currency = "USD"
            )
        )
        insert(
            tx(
                "USD2", profileId = profileId, amount = "50.00",
                type = TransactionType.INCOME, currency = "USD"
            )
        )
        insert(
            tx(
                "EUR1", profileId = profileId, amount = "80.00",
                type = TransactionType.INCOME, currency = "EUR"
            )
        )

        val result = service.aggregate(
            profileId = profileId,
            dimensions = listOf(AggregationDimension.CURRENCY),
            metrics = listOf(StandardMetrics.INCOME_SUM),
        )

        assertNotNull(result.getOrNull())
        val rows = result.getOrThrow()
        assertEquals(2, rows.size)

        val usd = rows.first { it.dimensions[AggregationDimension.CURRENCY] == "USD" }
        val eur = rows.first { it.dimensions[AggregationDimension.CURRENCY] == "EUR" }

        assertEquals(0, BigDecimal("150.00").compareTo(usd.metrics["income"]))
        assertEquals(0, BigDecimal("80.00").compareTo(eur.metrics["income"]))
    }

    @Test
    fun aggregate_isolatesProfileData() = runBlocking {
        insert(
            tx(
                "P1", profileId = profileId, amount = "200.00",
                type = TransactionType.INCOME, currency = "USD"
            )
        )
        insert(
            tx(
                "P2", profileId = otherProfileId, amount = "999.00",
                type = TransactionType.INCOME, currency = "USD"
            )
        )

        val result = service.aggregate(
            profileId = profileId,
            dimensions = listOf(AggregationDimension.CURRENCY),
            metrics = listOf(StandardMetrics.INCOME_SUM),
        )

        val rows = result.getOrThrow()
        assertEquals(1, rows.size)
        assertEquals(0, BigDecimal("200.00").compareTo(rows[0].metrics["income"]))
    }

    @Test
    fun aggregate_separatesIncomeAndExpenseMetrics() = runBlocking {
        insert(
            tx(
                "Income", profileId = profileId, amount = "500.00",
                type = TransactionType.INCOME, currency = "USD"
            )
        )
        insert(
            tx(
                "Expense", profileId = profileId, amount = "-200.00",
                type = TransactionType.EXPENSE, currency = "USD"
            )
        )

        val result = service.aggregate(
            profileId = profileId,
            dimensions = listOf(AggregationDimension.CURRENCY),
            metrics = listOf(StandardMetrics.INCOME_SUM, StandardMetrics.EXPENSE_SUM),
        )

        val row = result.getOrThrow().first()
        assertEquals(0, BigDecimal("500.00").compareTo(row.metrics["income"]))
        assertEquals(0, BigDecimal("-200.00").compareTo(row.metrics["expense"]))
    }

    // ─────────────────────────────────────────────────────────────────────────
    // Helpers
    // ─────────────────────────────────────────────────────────────────────────

    private suspend fun insert(entity: TransactionEntity) {
        db.transactionDao()._insertTransaction(entity)
    }

    private fun tx(
        name: String,
        profileId: Int = this.profileId,
        amount: String,
        type: TransactionType,
        currency: String = "USD",
        timestamp: Long = System.currentTimeMillis(),
    ) = TransactionEntity(
        name = name,
        amount = BigDecimal(amount),
        timestamp = timestamp,
        currency = currency,
        transactionType = type,
        accountId = "acc1",
        categoryId = 1L,
        profileId = profileId,
    )
}
